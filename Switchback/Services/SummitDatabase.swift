import CoreLocation
import Foundation
import SQLite3

/// A summit from the bundled reference database (USGS GNIS).
struct SummitRecord: Identifiable, Hashable, Sendable {
    let id: Int64
    let name: String
    let elevationMeters: Double?
    let latitude: Double
    let longitude: Double
    let state: String
    let county: String

    var coordinate: CLLocationCoordinate2D {
        CLLocationCoordinate2D(latitude: latitude, longitude: longitude)
    }

    var region: String {
        switch (county.isEmpty, state.isEmpty) {
        case (false, false): "\(county) County, \(state)"
        case (true, false): state
        default: ""
        }
    }
}

/// Read-only access to the bundled summits.sqlite, regenerated by
/// tools/build_summit_db.py. Reference data lives here, not in SwiftData —
/// the user's Summit records only store visits.
final class SummitDatabase: @unchecked Sendable {
    static let shared = SummitDatabase()

    private var db: OpaquePointer?
    private let queue = DispatchQueue(label: "com.jaylenkorth.switchback.summitdb")

    private init() {
        guard let url = Bundle.main.url(forResource: "summits", withExtension: "sqlite") else {
            return
        }
        var handle: OpaquePointer?
        if sqlite3_open_v2(url.path, &handle, SQLITE_OPEN_READONLY, nil) == SQLITE_OK {
            db = handle
        } else {
            sqlite3_close(handle)
        }
    }

    /// Summits inside a bounding box, tallest first.
    func summits(
        minLatitude: Double, maxLatitude: Double,
        minLongitude: Double, maxLongitude: Double,
        limit: Int = 100
    ) -> [SummitRecord] {
        queue.sync {
            guard let db else { return [] }
            let sql = """
                SELECT id, name, elevation_m, lat, lon, state, county FROM summits
                WHERE lat BETWEEN ? AND ? AND lon BETWEEN ? AND ?
                ORDER BY ifnull(elevation_m, -1) DESC LIMIT ?
                """
            var statement: OpaquePointer?
            guard sqlite3_prepare_v2(db, sql, -1, &statement, nil) == SQLITE_OK else { return [] }
            defer { sqlite3_finalize(statement) }

            sqlite3_bind_double(statement, 1, minLatitude)
            sqlite3_bind_double(statement, 2, maxLatitude)
            sqlite3_bind_double(statement, 3, minLongitude)
            sqlite3_bind_double(statement, 4, maxLongitude)
            sqlite3_bind_int(statement, 5, Int32(limit))

            var results: [SummitRecord] = []
            while sqlite3_step(statement) == SQLITE_ROW {
                guard let namePointer = sqlite3_column_text(statement, 1) else { continue }
                let elevation: Double? = sqlite3_column_type(statement, 2) == SQLITE_NULL
                    ? nil
                    : sqlite3_column_double(statement, 2)
                results.append(SummitRecord(
                    id: sqlite3_column_int64(statement, 0),
                    name: String(cString: namePointer),
                    elevationMeters: elevation,
                    latitude: sqlite3_column_double(statement, 3),
                    longitude: sqlite3_column_double(statement, 4),
                    state: sqlite3_column_text(statement, 5).map { String(cString: $0) } ?? "",
                    county: sqlite3_column_text(statement, 6).map { String(cString: $0) } ?? ""
                ))
            }
            return results
        }
    }

    /// Best reference record for a recorded summit visit: exact name match
    /// nearby, else nearest peak within 300 m, else a record synthesized
    /// from the visit itself (so the page still works offline-of-catalog).
    func record(matching visit: Summit) -> SummitRecord {
        let nearby = summits(
            minLatitude: visit.latitude - 0.01, maxLatitude: visit.latitude + 0.01,
            minLongitude: visit.longitude - 0.013, maxLongitude: visit.longitude + 0.013,
            limit: 50
        )
        if let named = nearby.first(where: { $0.name == visit.name }) {
            return named
        }
        let visitLocation = CLLocation(latitude: visit.latitude, longitude: visit.longitude)
        let nearest = nearby.min {
            visitLocation.distance(from: CLLocation(latitude: $0.latitude, longitude: $0.longitude))
                < visitLocation.distance(from: CLLocation(latitude: $1.latitude, longitude: $1.longitude))
        }
        if let nearest,
           visitLocation.distance(from: CLLocation(latitude: nearest.latitude, longitude: nearest.longitude)) < 300 {
            return nearest
        }
        return SummitRecord(
            id: Int64(truncatingIfNeeded: visit.name.hashValue),
            name: visit.name,
            elevationMeters: visit.elevationMeters,
            latitude: visit.latitude,
            longitude: visit.longitude,
            state: visit.region ?? "",
            county: ""
        )
    }

    /// Summits within `radiusMeters` of a track's bounding box.
    func summits(nearTrack track: [TrackPoint], radiusMeters: Double) -> [SummitRecord] {
        guard let minLat = track.map(\.latitude).min(),
              let maxLat = track.map(\.latitude).max(),
              let minLon = track.map(\.longitude).min(),
              let maxLon = track.map(\.longitude).max() else {
            return []
        }
        let latMargin = radiusMeters / 111_000
        let midLatitudeRadians = (minLat + maxLat) / 2 * .pi / 180
        let lonMargin = radiusMeters / (111_000 * max(0.1, cos(midLatitudeRadians)))
        return summits(
            minLatitude: minLat - latMargin,
            maxLatitude: maxLat + latMargin,
            minLongitude: minLon - lonMargin,
            maxLongitude: maxLon + lonMargin,
            limit: 500
        )
    }
}
